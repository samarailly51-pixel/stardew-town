/** 按 id 取居民，找不到就报错（写错 id 时能立刻发现） */
export function getCharacter(id) {
  const c = CHARACTERS.find((x) => x.id === id);
  if (!c) throw new Error(`没有这位居民：${id}`);
  return c;
}

/** 好感度 → 心数（每 25 点一颗心，最多 5 颗） */
export function heartsOf(points) {
  return Math.max(0, Math.min(5, Math.floor((points ?? 0) / 25)));
}

export function heartsStr(points) {
  const n = heartsOf(points);
  return '♥'.repeat(n) + '♡'.repeat(5 - n);
}
